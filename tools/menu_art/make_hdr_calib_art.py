# HDR CALIBRATION screen art for the renderer (d3d9_sod_calib.cpp): one alpha atlas with every string and the digits,
# and a small parchment texture. Output: sod-dxvk/src/d3d9/d3d9_sod_calib_art.h (atlas run-length encoded).
from PIL import Image, ImageDraw, ImageFont, ImageFilter
import random
S=3                                  # atlas pixels per menu unit (the menu is 640 x 480 units)
W,H=2048,1024
LABEL=ImageFont.truetype('/home/claude/sod/assets/fonts/Belleza-Regular.ttf',21*S)
TITLE=ImageFont.truetype('/home/claude/sod/assets/fonts/Belleza-Regular.ttf',31*S)
HELP=ImageFont.truetype('/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf',15*S)
atlas=Image.new('L',(W,H),0); d=ImageDraw.Draw(atlas)
d.rectangle([0,0,7,7],fill=255)      # white block for plain quads
x,y,rowh=16,0,0
rects={}
def put(name,text,font):
    global x,y,rowh
    l,t,r,b=font.getbbox(text); asc,desc=font.getmetrics(); w=r-l+4; h=asc+desc+2
    if x+w>W: x=0; y+=rowh+2; rowh=0
    d.text((x+2-l,y+1),text,font=font,fill=255)
    rects[name]=(x,y,w,h); x+=w+2; rowh=max(rowh,h)
put('title','HDR CALIBRATION',TITLE)
for n,t in [('l0','WHITE LEVEL'),('l1','PEAK BRIGHTNESS'),('l2','HIGHLIGHTS'),('l3','GAMMA'),('l4','SATURATION'),('l5','DEFAULT'),('l6','EXIT'),('nits','nits')]: put(n,t,LABEL)
for ch in '0123456789': put('d'+ch,ch,LABEL)
put('dot','.',LABEL); put('pct','%',LABEL)
helps=["Brightness of the game's white. Match it to the picture with HDR off.",
       "The brightest your display can show. Lights never go above this.",
       "How far lamps and glows rise above white. 0 leaves them at white.",
       "Depth of shadows and midtones. Higher is darker and richer.",
       "Colour strength. 100 is the original picture.",
       "Return every slider to its default.",
       "Save and return to GRAPHIC SETTING."]
for i,t in enumerate(helps): put('h%d'%i,t,HELP)
put('keys','UP and DOWN : select      LEFT and RIGHT : adjust      back : save and return',HELP)
put('capscene','Preview: the last scene you played',HELP)
put('cappat','Preview: test pattern (play the game once to see a scene here)',HELP)
put('title_gs','GRAPHIC SETTING',TITLE)
# whole fonts (ASCII 33..126) for texts the menu supplies at run time: glyph cell, origin offset, advance
fonts={}
def putfont(name,font):
    global x,y,rowh
    asc,desc=font.getmetrics(); h=asc+desc+2; g=[]
    for code in range(32,127):
        ch=chr(code); adv=font.getlength(ch)
        if code==32: g.append((0,0,0,0,0,adv)); continue
        l,t,r,b=font.getbbox(ch); ox=2-min(l,0); w=int(max(r,adv))+ox+3
        if x+w>W: x=0; y+=rowh+2; rowh=0
        d.text((x+ox,y+1),ch,font=font,fill=255)
        g.append((x,y,w,h,ox,adv)); x+=w+2; rowh=max(rowh,h)
    fonts[name]=(h,g)
x=0; y+=rowh+2; rowh=0
putfont('Label',LABEL); putfont('Help',HELP)
assert y+rowh<H,(y,rowh)
atlas.save('/tmp/hdr_calib_atlas.png')
# parchment: blotchy noise in the menu's colours
random.seed(7); PW,PH=160,80
n=Image.new('L',(PW//4,PH//4)); n.putdata([random.randint(0,255) for _ in range(PW//4*PH//4)])
n=n.resize((PW,PH),Image.BICUBIC).filter(ImageFilter.GaussianBlur(3))
f=Image.new('L',(PW,PH)); f.putdata([random.randint(110,145) for _ in range(PW*PH)])
par=Image.new('RGB',(PW,PH)); px=par.load(); nn=n.load(); ff=f.load()
lo,hi=min(n.getdata()),max(n.getdata())
for j in range(PH):
    for i in range(PW):
        t=(nn[i,j]-lo)/max(1,hi-lo); g=(ff[i,j]-128)/255*0.06
        a=(244,216,186); b=(214,172,128)
        px[i,j]=tuple(max(0,min(255,int((a[k]*t+b[k]*(1-t))*(1+g)))) for k in range(3))
par.save('/tmp/hdr_calib_parchment.png')
# run-length encode the atlas: (count 1..255, value)
data=atlas.tobytes(); rle=bytearray(); i=0
while i<len(data):
    v=data[i]; j=i
    while j<len(data) and data[j]==v and j-i<255: j+=1
    rle+=bytes((j-i,v)); i=j
with open('/home/claude/sod-dxvk/src/d3d9/d3d9_sod_calib_art.h','w') as o:
    o.write('// generated by sod/scripts/make_hdr_calib_art.py - HDR CALIBRATION screen art\n#pragma once\n#include <cstdint>\nnamespace dxvk::sodcal {\n')
    o.write('constexpr int kAtlasW = %d, kAtlasH = %d, kScale = %d, kParW = %d, kParH = %d;\n'%(W,H,S,PW,PH))
    o.write('struct Rect { uint16_t u, v, w, h; };\n')
    for k,r in rects.items(): o.write('constexpr Rect k_%s = { %d, %d, %d, %d };\n'%(k,*r))
    o.write('constexpr Rect kDigits[10] = { %s };\n'%', '.join('k_d%d'%i for i in range(10)))
    o.write('constexpr Rect kLabels[7] = { %s };\n'%', '.join('k_l%d'%i for i in range(7)))
    o.write('constexpr Rect kHelps[7] = { %s };\n'%', '.join('k_h%d'%i for i in range(7)))
    o.write('struct Glyph { uint16_t u, v, w, h; float ox, adv; };\n')
    for k,(h,g) in fonts.items():
        o.write('constexpr int kFont%sH = %d;\n'%(k,h))
        o.write('constexpr Glyph kFont%s[95] = {\n'%k+''.join('  { %d, %d, %d, %d, %.1ff, %.2ff },\n'%t for t in g)+'};\n')
    def arr(name,b):
        o.write('static const uint8_t %s[%d] = {\n'%(name,len(b)))
        for i in range(0,len(b),32): o.write(','.join(str(c) for c in b[i:i+32])+',\n')
        o.write('};\n')
    arr('kAtlasRle',rle); arr('kParchment',par.tobytes())
    o.write('}\n')
print(len(rle),y+rowh,rects['title'],rects['l1'],rects['h0'])
